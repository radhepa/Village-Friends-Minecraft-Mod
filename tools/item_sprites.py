    if name == 'smelling_salts':return raster(SALTS,GLASS)
    if name == 'revival_tonic':return raster(TONIC,dict(GLASS,s='558558',S='91BA7F',d='39634C',a='294E43'))
    if name == 'bandage_wrap':return raster(BANDAGE,LINEN)
    if name == 'steaming_coffee_mug':return raster(MUG,CERAMIC)
    if name == 'empty_coffee_mug':
        pattern=MUG.splitlines()
        pattern[2]='................';pattern[3]='................';pattern[4]='................'
        return raster('\n'.join(pattern),dict(CERAMIC,c='7E6245',b='6B523A'))
    if name == 'fresh_village_bread':return raster(BREAD,WHEAT)
    if name == 'hearty_stew':return raster(STEW,SOUP)
    if name == 'broom':return raster(BROOM,STRAW)
    if name == 'paintbrush':return raster(BRUSH,BRISTLE)
    if name == 'carpenter_hammer':return raster(HAMMER,IRON)
    if name == 'lute':return raster(LUTE,LUTHIER)
    if name == 'field_journal':return raster(JOURNAL,PAPER)
    raise ValueError('No authored sprite: '+name)
