def item_sprite(name):
    if name.endswith('_uniform'):return uniform(name.removesuffix('_uniform'))
    if name == 'rain_cloak':return raster(CLOAK, dict(zip('oHhmdbtT',('263C43','8CA8AE','608A95','467483','335D6D','264652','5B7771','BAC4A3'))))
