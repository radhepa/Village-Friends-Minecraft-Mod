def uniform(job):
    image = raster(UNIFORM, dict(zip('oHhmdbtT', GARMENTS[job])))
    colors = {k:tuple(bytes.fromhex(v))+(255,) for k,v in dict(zip('oHhmdbtT',GARMENTS[job])).items()}
    def pixel(x,y,s):image.putpixel((x,y),colors[s])
    # Job details are placed on the chest and respect its existing shaded silhouette.
    if job == 'knight':
        for x,y in [(4,7),(11,7),(5,12),(10,12)]:pixel(x,y,'H')
        for y in range(7,11):pixel(8,y,'h');pixel(9,y,'d')
    elif job == 'archer':
        for x,y in [(5,6),(6,7),(7,8),(8,9),(9,10),(10,11)]:pixel(x,y,'t')
    elif job == 'cook':
        for x in range(5,11):pixel(x,8,'H');pixel(x,9,'h')
        for y in range(10,14):pixel(6,y,'H');pixel(9,y,'h')
    elif job == 'tavern_keeper':
        for y in range(7,11):pixel(7,y,'T');pixel(8,y,'t')
        pixel(9,9,'H')
    elif job == 'apothecary':
        for y in range(8,11):pixel(8,y,'T')
        for x in range(7,10):pixel(x,9,'T')
    elif job == 'painter':
        pixel(6,8,'T');pixel(6,9,'t');pixel(10,10,'t');pixel(9,10,'T');pixel(5,12,'H')
    elif job == 'bard':
        for x in range(5,11):pixel(x,12,'t')
        for x,y in [(5,8),(6,9),(9,9),(10,8)]:pixel(x,y,'T')
    elif job == 'tailor':
        for x in range(6,10):pixel(x,10,'t')
        pixel(6,9,'T');pixel(9,9,'T');pixel(8,7,'H')
    elif job == 'carpenter':
        for x in range(5,8):pixel(x,9,'d');pixel(x,10,'b')
        pixel(9,9,'T');pixel(9,10,'t')
    elif job == 'scholar':
        for x in range(8,11):pixel(x,8,'t');pixel(x,9,'T');pixel(x,10,'t')
    return image


